package ru.severmax.control

/** Коды неисправностей из инструкции (стр. 28-29): код, описание, рекомендации. */
object ErrorCodes {
    val all: List<Triple<String, String, String>> = listOf(
        Triple("E-01", "Ненормальное напряжение", "Проверить напряжение аккумулятора."),
        Triple("E-02", "Неисправность нагнетателя", "Проверить жгуты на повреждения, обрывы и КЗ. Проверить нагнетатель, загрязнение и свободный ход вентилятора, при необходимости заменить."),
        Triple("E-03", "Неисправность топливного насоса", "Проверить жгуты на повреждения, обрывы и КЗ. Функциональная проверка насоса, при необходимости заменить."),
        Triple("E-04", "Неисправность жидкостного насоса", "Проверить жгуты. Функциональная проверка насоса, почистить насосную часть помпы, при необходимости заменить."),
        Triple("E-05", "Срыв пламени", "При частом возникновении (>10 раз): забор воздуха или отвод выхлопных газов, топливная система, насос-дозатор, электросистема штифта накала."),
        Triple("E-06", "Неисправность датчика пламени", "Проверить жгуты на повреждения, обрывы и КЗ. Проверить сопротивление датчика пламени, при необходимости заменить."),
        Triple("E-07", "Неисправность штифта накала", "Проверить жгуты на повреждения, обрывы и КЗ. Функциональная проверка штифта накала, при необходимости заменить."),
        Triple("E-08", "Сбой вторичного запуска", "При частом возникновении (>5 раз): забор воздуха или отвод выхлопных газов, топливная система, насос-дозатор, электросистема штифта накала."),
        Triple("E-09", "Неисправность датчика температуры охлаждающей жидкости", "Проверить жгуты на повреждения, обрывы и КЗ. Проверить сопротивление датчика, при необходимости заменить."),
        Triple("E-10", "Перегрев корпуса подогревателя", "Проверить жгуты и сопротивление датчика, при необходимости заменить."),
        Triple("E-11", "Перегрев охлаждающей жидкости", "Информационная ошибка. При частом возникновении: уровень жидкости и воздух в контуре, циркуляционный насос, датчик температуры (E-09), качество антифриза (не должен быть густым)."),
        Triple("E-12", "Обрыв связи дистанционного пульта с салонным", "Антенна прикручена к салонному пульту; дистанционный пульт привязан к салонному; расстояние не более 100 м прямой видимости.")
    )

    private val regex = Regex("\\bE-?(\\d{1,2})\\b", RegexOption.IGNORE_CASE)

    fun find(text: String): Triple<String, String, String>? {
        val m = regex.find(text) ?: return null
        val code = "E-" + m.groupValues[1].padStart(2, '0')
        return all.firstOrNull { it.first == code }
    }
}
